"""Speak text with Kokoro-82M, a small open text-to-speech model (Apache 2.0), run locally.

The whole narration uses one voice (Kokoro's `am_puck`); only the closing line gets a robot effect, as a
"yes, this was AI" ending. Other voices are kept in CAST for trying alternatives.

  distrobox enter gpu -- ~/.venvs/tts/bin/python voices.py               -> narration/<shot>.wav (the video's voice)
  distrobox enter gpu -- ~/.venvs/tts/bin/python voices.py --samples     -> samples/ (voice try-outs)

make_video.py picks up narration/title.wav, narration/1.wav ... narration/end.wav by itself.
"""

from __future__ import annotations

import shutil
import subprocess
import sys
from pathlib import Path

HERE = Path(__file__).parent
RATE = 24_000  # Kokoro's sample rate
# Kokoro runs in the `gpu` container, which has no ffmpeg: use the host's.
FFMPEG = ["ffmpeg"] if shutil.which("ffmpeg") else ["distrobox-host-exec", "ffmpeg"]

# role: (Kokoro voice, language code a = American / b = British, speed)
NARRATOR = ("am_puck", "a", 1.1)  # the chosen narration voice (voice, language, speed)

CAST = {
    "narrator": NARRATOR,
    "mission-control": ("af_nova", "a", 1.1),
    "router": ("am_puck", "a", 1.2),
    "opus": ("am_onyx", "a", 0.92),
    "worker": ("bf_lily", "b", 1.0),
}

SAMPLES = {
    "narrator": "This is Mission Control: one hub for all my coding agents, including a model that runs on my own GPU.",
    "mission-control": "Ollama started. Model loaded. GPU at nine point one gigabytes.",
    "router": "Local. Fifty milliseconds.",
    "opus": "I'll take this one. Worker: the local model. Time limit: ten minutes.",
    "worker": "Done. I added the option, and all tests pass.",
}

# What is said over each part of the video: the title card, shots 1-9 (see VIDEO.md), the end card.
# Written as it should be SPOKEN (numbers in words), because the model reads exactly what it gets.
NARRATION = {
    "title": "This is an agentic coding system, built for the six-two-six portfolio.",
    "1": "This is Mission Control: one hub for all the coding agents, including a model that runs on the local GPU.",
    "2": "Every panel is live: the projects and their git status, dispatched tasks, plan usage, containers, "
         "the local model, and every running agent.",
    "3": "Pressing O starts Ollama, the local model server. The model loads straight onto the GPU.",
    "4": "Pressing four opens Codex on the local model. The same agent, on local hardware: free, offline and private.",
    "5": "Next, Dispatch. A task is described, the fine-tuned router answers instantly, "
         "and then Opus plans the job and writes the brief.",
    "6": "The worker gets its own copy of the project, a git worktree, so the real code stays untouched. "
         "It also runs with a time limit.",
    "7": "When the worker is done, Opus reviews the change. The review and the diff are checked before anything is merged.",
    "8": "The router is Gemma 4, fine-tuned with Unsloth. Balanced accuracy rose from fifty-two to sixty-three percent: "
         "as good as a nine billion parameter model that thinks first, and about a hundred times faster.",
    "9": "The design, the usage guide and every experiment are documented in the portfolio repo.",
    "end": "This narration was generated by Kokoro, an open-source voice model with eighty-two million parameters, "
           "running locally on the same GPU. The video was edited by a script written by Claude Code.",
}

# Only the closing line of the video gets the robot effect.
ROBOT_LAST_LINE = True

# A "robot" voice: the phase of every frequency is set to zero, which removes the natural pitch movement.
ROBOT_FILTER = "afftfilt=real='hypot(re,im)*sin(0)':imag='hypot(re,im)*cos(0)':win_size=512:overlap=0.75"


_PIPELINES: dict[tuple[str, str], object] = {}


def default_device() -> str:
    try:
        import torch
        return "cuda" if torch.cuda.is_available() else "cpu"
    except ImportError:
        return "cpu"


def speak(role: str, text: str, out: Path, device: str | None = None) -> Path:
    """Write `text` in `role`'s voice to a WAV file (on the GPU when there is one)."""
    import numpy as np
    import soundfile as sf
    from kokoro import KPipeline

    voice, lang, speed = CAST[role]
    key = (lang, device or default_device())
    if key not in _PIPELINES:  # loading the model takes a few seconds: do it once per language
        _PIPELINES[key] = KPipeline(lang_code=lang, device=key[1])
    pipeline = _PIPELINES[key]
    audio = np.concatenate([chunk for _, _, chunk in pipeline(text, voice=voice, speed=speed)])
    out.parent.mkdir(parents=True, exist_ok=True)
    sf.write(out, audio, RATE)
    return out


def robotize(src: Path, out: Path) -> Path:
    subprocess.run([*FFMPEG, "-hide_banner", "-loglevel", "error", "-y", "-i", str(src), "-af", ROBOT_FILTER, str(out)],
                   check=True)
    return out


def samples() -> None:
    folder = HERE / "samples"
    files = []
    for role, text in SAMPLES.items():
        files.append(speak(role, text, folder / f"{role}.wav"))
        print(f"{role:<16} {CAST[role][0]:<10} {files[-1]}")
    files.append(robotize(folder / "mission-control.wav", folder / "mission-control-robot.wav"))
    print(f"{'robot version':<16} {'':<10} {files[-1]}")
    # All of them in a row, with half a second between, to hear the cast together.
    gap = folder / "gap.wav"
    subprocess.run([*FFMPEG, "-hide_banner", "-loglevel", "error", "-y", "-f", "lavfi", "-i",
                    f"anullsrc=r={RATE}:cl=mono", "-t", "0.6", str(gap)], check=True)
    listing = folder / "cast.txt"
    listing.write_text("".join(f"file '{f.name}'\nfile 'gap.wav'\n" for f in files))
    subprocess.run([*FFMPEG, "-hide_banner", "-loglevel", "error", "-y", "-f", "concat", "-safe", "0", "-i",
                    str(listing), "-c:a", "pcm_s16le", str(folder / "cast.wav")], check=True)
    print(f"\nall together: {folder / 'cast.wav'}")


def speed_samples() -> None:
    """The opening line at two speeds, and a robot-voice closing line, to choose from."""
    folder = HERE / "samples"
    opening = "This is Mission Control: one hub for all my coding agents, including a model that runs on my own GPU."
    closing = "This video was narrated by a voice model running on the same GPU."
    files = []
    for speed in (1.0, 1.1):
        CAST["narrator"] = (NARRATOR[0], NARRATOR[1], speed)
        files.append(speak("narrator", opening, folder / f"puck-{speed}.wav"))
    CAST["narrator"] = NARRATOR
    files.append(robotize(speak("narrator", closing, folder / "puck-closing.wav"), folder / "puck-closing-robot.wav"))
    listing = folder / "puck.txt"
    listing.write_text("".join(f"file '{f.name}'\nfile 'gap.wav'\n" for f in files))
    subprocess.run([*FFMPEG, "-hide_banner", "-loglevel", "error", "-y", "-f", "concat", "-safe", "0", "-i",
                    str(listing), "-c:a", "pcm_s16le", str(folder / "puck-compare.wav")], check=True)
    print(folder / "puck-compare.wav")


def narrate() -> None:
    """Speak every NARRATION line into narration/<key>.wav; the closing line gets the robot effect."""
    folder = HERE / "narration"
    print(f"Kokoro on {default_device()}")
    for key, text in NARRATION.items():
        out = folder / f"{key}.wav"
        if key == "end" and ROBOT_LAST_LINE:
            robotize(speak("narrator", text, folder / "end-natural.wav"), out)
        else:
            speak("narrator", text, out)
        print(f"{out.name:<10} {text[:70]}")


if __name__ == "__main__":
    if "--samples" in sys.argv:
        samples()
    elif "--speed-samples" in sys.argv:
        speed_samples()
    else:
        narrate()
